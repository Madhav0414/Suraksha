import { useEffect, useState } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { fetchReport } from "../api";

export default function IncidentReportModal({ onClose }) {
  const [markdown, setMarkdown] = useState(null);
  const [error, setError] = useState(false);

  useEffect(() => {
    fetchReport()
      .then((r) => setMarkdown(r.markdown))
      .catch(() => setError(true));
  }, []);

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-6"
      onClick={onClose}
    >
      <div
        className="report max-h-[88vh] w-full max-w-3xl overflow-y-auto rounded-xl border border-slate-700 bg-[#0f172a] p-8 shadow-2xl"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="mb-4 flex items-center justify-between print:hidden">
          <span className="text-[11px] font-semibold uppercase tracking-[0.18em] text-rose-400">
            ● Auto-generated by Emergency Response Orchestrator
          </span>
          <div className="flex gap-2">
            <button
              onClick={() => window.print()}
              className="rounded-md border border-slate-700 px-3 py-1.5 text-xs text-slate-300 hover:border-cyan-500 hover:text-cyan-300"
            >
              🖨 Print / PDF
            </button>
            <button
              onClick={onClose}
              className="rounded-md border border-slate-700 px-3 py-1.5 text-xs text-slate-300 hover:border-rose-500 hover:text-rose-300"
            >
              ✕ Close
            </button>
          </div>
        </div>
        {error && (
          <p className="text-sm text-slate-400">No incident report available yet.</p>
        )}
        {markdown && (
          <ReactMarkdown remarkPlugins={[remarkGfm]}>{markdown}</ReactMarkdown>
        )}
      </div>
    </div>
  );
}
